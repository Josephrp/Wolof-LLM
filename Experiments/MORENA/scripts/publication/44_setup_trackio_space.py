#!/usr/bin/env python3
"""Create/verify the private MORENA Trackio Gradio Space + Bucket.

Writes non-secret IDs to results/full_pipeline/trackio_env.json and
Experiments/MORENA/.env.trackio so CPT/SFT/distill/orchestrator runs sync
metrics into the Gradio dashboard.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
import tempfile
import time
import warnings
from datetime import UTC, datetime
from pathlib import Path

import trackio
from huggingface_hub import (
    HfApi,
    bucket_info,
    download_bucket_files,
    get_token,
    list_bucket_tree,
)
from huggingface_hub.errors import BucketNotFoundError
from trackio import deploy as trackio_deploy
from trackio.fragments import parse_fragment_bytes
from trackio.remote_client import RemoteClient
from trackio.server import get_run_summary
from trackio.sqlite_storage import SQLiteStorage

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from common.pipeline import atomic_json_write  # noqa: E402
from common.tracking import PROJECT, deterministic_run_name  # noqa: E402


def ensure_private_bucket(api: HfApi, bucket_id: str) -> None:
    try:
        info = api.bucket_info(bucket_id)
    except BucketNotFoundError:
        api.create_bucket(bucket_id, private=True)
    else:
        if info.private is not True:
            api.update_bucket_settings(bucket_id, private=True)
    if api.bucket_info(bucket_id).private is not True:
        raise RuntimeError("Trackio Bucket could not be made private")


def inspect_dashboard(api: HfApi, space_id: str) -> dict:
    try:
        runtime = api.get_space_runtime(space_id)
        raw_stage = getattr(runtime.stage, "value", runtime.stage)
        stage = str(raw_stage).upper()
        status = "running" if stage == "RUNNING" else ("paused" if stage == "PAUSED" else stage.lower())
        return {"stage": stage, "dashboard_status": status}
    except Exception as exc:  # noqa: BLE001
        return {
            "stage": "UNKNOWN",
            "dashboard_status": "runtime_query_unavailable",
            "warning": type(exc).__name__,
        }


def verify_bucket_persistence(
    *,
    bucket_id: str,
    project: str,
    run_name: str,
    run_id: str,
    token: str,
    timeout: float = 120,
) -> dict:
    info = bucket_info(bucket_id, token=token)
    if info.private is not True:
        raise RuntimeError("Trackio Bucket is not private")
    deadline = time.monotonic() + timeout
    while True:
        files = [
            item
            for item in list_bucket_tree(
                bucket_id,
                prefix="trackio/inbox",
                recursive=True,
                token=token,
            )
            if getattr(item, "type", None) == "file"
            and str(getattr(item, "path", "")).endswith(".jsonl")
        ]
        for item in files:
            with tempfile.TemporaryDirectory(prefix="trackio-bucket-readback-") as temporary:
                destination = Path(temporary) / "fragment.jsonl"
                download_bucket_files(
                    bucket_id,
                    files=[(item, destination)],
                    token=token,
                )
                payload = destination.read_bytes()
            for record in parse_fragment_bytes(payload):
                if (
                    record.get("kind") == "metric"
                    and record.get("project") == project
                    and record.get("run") == run_name
                    and record.get("run_id") == run_id
                    and record.get("metrics", {}).get("sync_smoke") == 1
                ):
                    return {
                        "status": "verified",
                        "bucket_id": bucket_id,
                        "private": True,
                        "fragment_path": item.path,
                        "fragment_sha256": hashlib.sha256(payload).hexdigest(),
                    }
        if time.monotonic() >= deadline:
            raise RuntimeError("Trackio smoke run was not readable from the private Bucket")
        time.sleep(2)


def write_dotenv(space_id: str, bucket_id: str, dataset_id: str | None) -> Path:
    path = ROOT / ".env.trackio"
    lines = [
        "# Auto-generated by scripts/publication/44_setup_trackio_space.py",
        f"TRACKIO_PROJECT={PROJECT}",
        f"TRACKIO_SPACE_ID={space_id}",
        f"TRACKIO_BUCKET_ID={bucket_id}",
    ]
    if dataset_id:
        lines.append(f"TRACKIO_DATASET_ID={dataset_id}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def main() -> int:
    parser = argparse.ArgumentParser(description="Set up MORENA Trackio Gradio Space")
    parser.add_argument("--preferred-namespace", default="Tonic")
    parser.add_argument("--space-name", default="morena-wolof-trackio")
    parser.add_argument(
        "--out",
        type=Path,
        default=ROOT / "results" / "full_pipeline" / "trackio_space.json",
    )
    parser.add_argument(
        "--env-out",
        type=Path,
        default=ROOT / "results" / "full_pipeline" / "trackio_env.json",
    )
    args = parser.parse_args()

    token = os.environ.get("HF_TOKEN") or get_token()
    if not token:
        raise SystemExit("Hugging Face authentication is required")
    api = HfApi(token=token)
    who = api.whoami()
    namespace = args.preferred_namespace
    orgs = {org.get("name") for org in (who.get("orgs") or []) if isinstance(org, dict)}
    if namespace not in orgs and who.get("name") != namespace:
        namespace = who["name"]
        print(f"[warn] falling back to personal namespace {namespace}")

    space_id = os.environ.get("TRACKIO_SPACE_ID") or f"{namespace}/{args.space_name}"
    bucket_id = os.environ.get("TRACKIO_BUCKET_ID") or f"{space_id}-bucket"
    dataset_id = os.environ.get("TRACKIO_DATASET_ID") or f"{space_id}-history"

    # Deploy Gradio Trackio app.py (bare create_repo leaves NO_APP_FILE).
    # Force deploy_as_space so an existing empty Space gets app.py/requirements.
    trackio_deploy.deploy_as_space(
        space_id,
        private=True,
        bucket_id=bucket_id,
    )
    info = api.repo_info(repo_id=space_id, repo_type="space")
    if info.private is not True:
        raise RuntimeError("Trackio Space is not private")

    dashboard = inspect_dashboard(api, space_id)
    ensure_private_bucket(api, bucket_id)

    api.create_repo(
        repo_id=dataset_id,
        repo_type="dataset",
        private=True,
        exist_ok=True,
    )

    timestamp = datetime.now(UTC).strftime("%Y%m%d-%H%M%S")
    run_name = deterministic_run_name(
        size="common",
        stage="trackio-smoke",
        tokenizer_family="none",
        method="sync",
        seed=42,
        run_id=timestamp,
    )
    run = trackio.init(
        project=PROJECT,
        name=run_name,
        group="common/trackio-smoke",
        config={"kind": "morena-private-space-sync-smoke", "seed": 42},
        space_id=space_id,
        bucket_id=bucket_id,
    )
    run_id = str(getattr(run, "id", run_name))
    if dashboard["dashboard_status"] != "running":
        message = (
            f"Live Trackio dashboard unavailable "
            f"({dashboard['dashboard_status']}); using verified private Bucket persistence"
        )
        warnings.warn(message, stacklevel=1)
        trackio.alert(
            title="Trackio dashboard degraded",
            text=message,
            level=trackio.AlertLevel.WARN,
        )
    trackio.log({"sync_smoke": 1, "gate_status": 1, "family": "morena"}, step=0)
    trackio.finish()

    persistence = verify_bucket_persistence(
        bucket_id=bucket_id,
        project=PROJECT,
        run_name=run_name,
        run_id=run_id,
        token=token,
    )
    local_db = SQLiteStorage.get_project_db_path(PROJECT)
    local_summary = get_run_summary(PROJECT, run_name, run_id=run_id)
    if not local_db.is_file() or local_db.stat().st_size == 0:
        raise RuntimeError("Trackio durable local database is missing")
    if local_summary.get("run") != run_name:
        raise RuntimeError("Trackio durable local query did not return the smoke run")

    live_query = {"status": "skipped", "reason": dashboard["dashboard_status"]}
    if dashboard["dashboard_status"] == "running":
        try:
            queried = RemoteClient(space_id, hf_token=token).predict(
                project=PROJECT,
                run=run_name,
                run_id=run_id,
                api_name="/get_run_summary",
            )
            if not isinstance(queried, dict) or queried.get("run") != run_name:
                raise RuntimeError("live dashboard query returned the wrong run")
            live_query = {"status": "verified"}
        except Exception as exc:  # noqa: BLE001
            live_query = {"status": "unavailable", "warning": type(exc).__name__}

    dashboard_url = f"https://huggingface.co/spaces/{space_id}"
    dotenv = write_dotenv(space_id, bucket_id, dataset_id)
    atomic_json_write(
        args.out if args.out.is_absolute() else ROOT / args.out,
        {
            "schema_version": 1,
            "project": PROJECT,
            "run_name": run_name,
            "run_id": run_id,
            "space_id": space_id,
            "bucket_id": bucket_id,
            "dataset_id": dataset_id,
            "dashboard_url": dashboard_url,
            "private": True,
            "dashboard": dashboard,
            "live_query": live_query,
            "bucket": persistence,
            "dotenv": str(dotenv),
            "verified_at": datetime.now(UTC).isoformat(),
        },
    )
    atomic_json_write(
        args.env_out if args.env_out.is_absolute() else ROOT / args.env_out,
        {
            "TRACKIO_PROJECT": PROJECT,
            "TRACKIO_SPACE_ID": space_id,
            "TRACKIO_BUCKET_ID": bucket_id,
            "TRACKIO_DATASET_ID": dataset_id,
        },
    )
    print(f"MORENA_TRACKIO_OK space={space_id} bucket={bucket_id} dashboard={dashboard_url}")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, RuntimeError, ValueError, json.JSONDecodeError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        raise SystemExit(1) from exc
