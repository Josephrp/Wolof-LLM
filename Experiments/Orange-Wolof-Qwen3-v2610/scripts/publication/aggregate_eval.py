#!/usr/bin/env python3
"""Aggregate Tier-1 CLM + GGUF metrics into results/FAMILY_EVAL.md.

Pattern: Qwen3.5-Wolof-Family/scripts/publication/56_publish_hub_metrics.py
(table generation part). BPB is the cross-tokenizer gold metric; PPL is only
compared within identical tokenizers. Also verifies Hub SHAs against
configs/family.yaml and warns loudly on mismatch (silent re-upload guard).
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import UTC, datetime

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
from pathlib import Path

import yaml
from huggingface_hub import HfApi

ROOT = Path(__file__).resolve().parents[2]
REPO = ROOT.parents[1]
EVAL_ROOT = REPO / "Evaluation"


def load_json(path: Path) -> dict | None:
    return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else None


def fmt(value, digits=4):
    return f"{value:.{digits}f}" if isinstance(value, (int, float)) else "—"


def main() -> int:
    parser = argparse.ArgumentParser(description="Build FAMILY_EVAL.md from metrics JSONs")
    parser.add_argument("--check-shas", action="store_true", help="verify Hub SHAs vs family.yaml (needs network)")
    args = parser.parse_args()

    family = yaml.safe_load((ROOT / "configs" / "family.yaml").read_text(encoding="utf-8"))
    warnings: list[str] = []

    if args.check_shas:
        api = HfApi()
        for size in family["sizes"]:
            try:
                live = (api.model_info(size["hub_id"]).sha or "")[:10]
            except Exception as exc:  # noqa: BLE001
                warnings.append(f"{size['hub_id']}: SHA check failed ({exc})")
                continue
            if live != size["sha"]:
                warnings.append(f"SHA MISMATCH {size['hub_id']}: pinned {size['sha']} != live {live}")

    rows = []
    for size in family["sizes"]:
        key = size["key"]
        orange = load_json(EVAL_ROOT / "metrics" / "clm" / f"orange_wolof_qwen3_{key}.json")
        base = load_json(EVAL_ROOT / "metrics" / "clm" / f"qwen3_{key}.json")
        gguf = load_json(EVAL_ROOT / "metrics" / "gguf" / f"orange_wolof_qwen3_{key}_q4_k_m.json")
        if not size.get("weights_present", True):
            rows.append(f"| {size['label']} | ⛔ BLOCKED — no weights on Hub | — | — | — | — | — |")
            continue
        rows.append(
            f"| {size['label']} | {fmt(orange and orange.get('BPB'))} vs {fmt(base and base.get('BPB'))} "
            f"| {fmt(orange and orange.get('BLEU'), 2)} | {fmt(orange and orange.get('chrF'), 2)} "
            f"| {fmt(base and base.get('chrF'), 2)} "
            f"| {fmt(gguf and gguf.get('chrF'), 2)} (Q4_K_M) | {fmt(gguf and gguf.get('perplexity'), 2)} |"
        )

    doc = f"""# Orange Wolof-Qwen3 v2610 — family eval table

Generated by `scripts/publication/aggregate_eval.py`. Protocol: `Evaluation/scripts/evaluate_clm.py`
(BPB = cross-tokenizer gold) on `Evaluation/data/corpus_test_clm.csv` (4,282 verbalized texts);
GGUF column: `evaluate_gguf.py` protocol `gguf-llama-cpp` (PPL not HF-comparable).
Full plan: `docs/EVALUATION_AND_QUANTIZATION_PLAN.md`.

| Size | BPB ↓ Orange vs stock Qwen3 | BLEU (Orange) | chrF (Orange) | chrF (stock) | chrF GGUF | GGUF PPL |
|---|---|---:|---:|---:|---:|---:|
{chr(10).join(rows)}

Updated: {datetime.now(UTC).isoformat()}
"""
    if warnings:
        doc += "\n## ⚠️ Warnings\n\n" + "\n".join(f"- {w}" for w in warnings) + "\n"
    out = ROOT / "results" / "FAMILY_EVAL.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(doc, encoding="utf-8")
    print(doc)
    print(f"[ok] {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
